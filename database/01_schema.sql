-- FitTrack core relational schema. Run with psql against an empty project database.
CREATE TABLE IF NOT EXISTS admins (
  admin_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email TEXT NOT NULL UNIQUE,
  password_hash TEXT NOT NULL,
  display_name TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CHECK (email = LOWER(email))
);

CREATE TABLE IF NOT EXISTS members (
  member_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  member_name TEXT NOT NULL CHECK (LENGTH(BTRIM(member_name)) BETWEEN 2 AND 120),
  email TEXT NOT NULL UNIQUE,
  phone TEXT NOT NULL UNIQUE,
  join_date DATE NOT NULL DEFAULT CURRENT_DATE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CHECK (email = LOWER(email))
);

CREATE TABLE IF NOT EXISTS trainers (
  trainer_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  trainer_name TEXT NOT NULL CHECK (LENGTH(BTRIM(trainer_name)) BETWEEN 2 AND 120),
  email TEXT NOT NULL UNIQUE,
  phone TEXT NOT NULL,
  specialization TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CHECK (email = LOWER(email))
);

CREATE TABLE IF NOT EXISTS membership_plans (
  plan_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  plan_name TEXT NOT NULL UNIQUE,
  duration_months INTEGER NOT NULL CHECK (duration_months BETWEEN 1 AND 60),
  price NUMERIC(10,2) NOT NULL CHECK (price > 0),
  description TEXT NOT NULL DEFAULT '',
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS subscriptions (
  subscription_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  member_id INTEGER NOT NULL REFERENCES members(member_id) ON DELETE RESTRICT,
  plan_id INTEGER NOT NULL REFERENCES membership_plans(plan_id) ON DELETE RESTRICT,
  trainer_id INTEGER REFERENCES trainers(trainer_id) ON DELETE SET NULL,
  start_date DATE NOT NULL,
  end_date DATE NOT NULL,
  status TEXT NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'EXPIRED', 'CANCELLED')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CHECK (end_date >= start_date)
);

CREATE TABLE IF NOT EXISTS payments (
  payment_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  subscription_id INTEGER NOT NULL REFERENCES subscriptions(subscription_id) ON DELETE RESTRICT,
  amount NUMERIC(10,2) NOT NULL CHECK (amount > 0),
  payment_date TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  payment_method TEXT NOT NULL CHECK (payment_method IN ('CASH', 'UPI', 'CARD', 'BANK_TRANSFER')),
  payment_status TEXT NOT NULL DEFAULT 'PAID' CHECK (payment_status IN ('PAID', 'PENDING', 'FAILED', 'REFUNDED')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS attendance (
  attendance_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  subscription_id INTEGER NOT NULL REFERENCES subscriptions(subscription_id) ON DELETE RESTRICT,
  check_in_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  check_out_at TIMESTAMPTZ,
  CHECK (check_out_at IS NULL OR check_out_at >= check_in_at)
);

CREATE TABLE IF NOT EXISTS payment_audit (
  audit_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  payment_id INTEGER NOT NULL REFERENCES payments(payment_id) ON DELETE RESTRICT,
  operation TEXT NOT NULL CHECK (operation IN ('INSERT', 'UPDATE')),
  old_values JSONB,
  new_values JSONB NOT NULL,
  changed_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  changed_by INTEGER REFERENCES admins(admin_id) ON DELETE SET NULL
);

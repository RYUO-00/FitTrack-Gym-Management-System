DO $$
DECLARE v_gym_id INTEGER; v_rows BIGINT; v_subscriptions BIGINT;
BEGIN
  IF EXISTS (SELECT 1 FROM information_schema.columns
             WHERE table_schema=current_schema() AND table_name='membership_plans' AND column_name='plan_id') THEN
    IF EXISTS (SELECT 1 FROM subscriptions s LEFT JOIN membership_plans p ON p.plan_id=s.plan_id
               WHERE p.plan_id IS NULL) THEN
      RAISE EXCEPTION 'Orphan plan references found; migration stopped without changing data';
    END IF;
    IF EXISTS (SELECT 1 FROM membership_plans WHERE plan_id <= 0) THEN
      RAISE EXCEPTION 'Existing plan IDs must be positive; migration stopped without changing data';
    END IF;
    SELECT COUNT(*) INTO v_rows FROM membership_plans;
    SELECT COUNT(*) INTO v_subscriptions FROM subscriptions;
    -- A conflicting name is reused only when it is the deliberately created default branch.
    INSERT INTO gyms(branch_name,address,phone,email)
    VALUES ('FitTrack Main Branch','Main Road, Mangaluru, Karnataka','+91-90000-30001','main@fittrack.example.test')
    ON CONFLICT (branch_name) DO NOTHING;
    SELECT gym_id INTO STRICT v_gym_id FROM gyms WHERE branch_name='FitTrack Main Branch';


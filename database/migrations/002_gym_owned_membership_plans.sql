    -- dependency error and roll back the entire transaction; CASCADE is never used.
    DROP VIEW IF EXISTS v_active_subscriptions;
    DROP PROCEDURE IF EXISTS create_subscription(INTEGER,INTEGER,INTEGER,DATE,INTEGER);
    DROP PROCEDURE IF EXISTS renew_subscription(INTEGER,INTEGER,INTEGER,DATE,INTEGER);
    ALTER TABLE subscriptions DROP CONSTRAINT subscriptions_plan_id_fkey;
    ALTER TABLE membership_plans DROP CONSTRAINT membership_plans_pkey;
    ALTER TABLE membership_plans DROP CONSTRAINT membership_plans_plan_name_key;
    ALTER TABLE membership_plans ALTER COLUMN plan_id DROP IDENTITY IF EXISTS;
    ALTER TABLE membership_plans RENAME COLUMN plan_id TO plan_no;
    ALTER TABLE subscriptions RENAME COLUMN plan_id TO plan_no;
    ALTER TABLE membership_plans ADD COLUMN gym_id INTEGER;
    ALTER TABLE subscriptions ADD COLUMN gym_id INTEGER;
    UPDATE membership_plans SET gym_id=v_gym_id;
    UPDATE subscriptions SET gym_id=v_gym_id;
    ALTER TABLE membership_plans ALTER COLUMN gym_id SET NOT NULL;
    ALTER TABLE subscriptions ALTER COLUMN gym_id SET NOT NULL;
    ALTER TABLE membership_plans ADD CONSTRAINT membership_plans_plan_no_check CHECK(plan_no > 0);
    ALTER TABLE membership_plans ADD PRIMARY KEY(gym_id,plan_no);
    ALTER TABLE membership_plans ADD UNIQUE(gym_id,plan_name);
    ALTER TABLE membership_plans ADD FOREIGN KEY(gym_id) REFERENCES gyms(gym_id) ON DELETE RESTRICT;
    ALTER TABLE subscriptions ADD FOREIGN KEY(gym_id,plan_no)
      REFERENCES membership_plans(gym_id,plan_no) ON DELETE RESTRICT;
    DROP INDEX IF EXISTS idx_subscriptions_plan;
    CREATE INDEX idx_subscriptions_plan ON subscriptions(gym_id,plan_no);
    IF v_rows <> (SELECT COUNT(*) FROM membership_plans) OR
       v_subscriptions <> (SELECT COUNT(*) FROM subscriptions) THEN
      RAISE EXCEPTION 'Row count mismatch; migration rolled back';
    END IF;
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid='membership_plans'::regclass
                 AND contype='p' AND pg_get_constraintdef(oid)='PRIMARY KEY (gym_id, plan_no)') OR
     NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid='subscriptions'::regclass
                 AND contype='f' AND confrelid='membership_plans'::regclass
                 AND pg_get_constraintdef(oid) LIKE 'FOREIGN KEY (gym_id, plan_no)%' AND convalidated) THEN
    RAISE EXCEPTION 'Unexpected partial schema; no changes committed. Inspect before repairing.';
  END IF;
END $$;


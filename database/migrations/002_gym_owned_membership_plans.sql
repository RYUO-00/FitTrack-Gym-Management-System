  address TEXT NOT NULL CHECK (LENGTH(BTRIM(address)) > 0),
  phone TEXT NOT NULL,
  email TEXT NOT NULL CHECK (email = LOWER(email)),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
